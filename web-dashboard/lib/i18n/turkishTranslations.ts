export function translateTurkishUiText(source: string): string {
  if (!source.trim()) return source;

  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const content = source.trim().replace(/\s+/g, " ");
  const exact = turkishPhrases[content];
  if (exact) return `${leading}${exact}${trailing}`;

  for (const template of templates) {
    const match = content.match(template.pattern);
    if (match) return `${leading}${template.render(...match.slice(1))}${trailing}`;
  }

  return source;
}

