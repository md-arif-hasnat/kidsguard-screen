export function translateUiText(source: string, locale: Locale): string {
  if (locale === "en" || !source.trim()) return source;

  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const content = source.trim().replace(/\s+/g, " ");
  const index = localeIndex[locale];
  const exact = phrases[content];
  if (exact) return `${leading}${exact[index]}${trailing}`;

  for (const template of templates) {
    const match = content.match(template.pattern);
    if (match) return `${leading}${template.render[locale](...match.slice(1))}${trailing}`;
  }

  return source;
}
